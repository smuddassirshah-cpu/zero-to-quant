"""Recompute every number in brainteasers homework-1 item hw9-l-pieces-6x10.

Claim: fifteen L-tetrominoes cannot cover a 6 x 10 board.
Route 1 is the colouring argument, checked square by square.
Route 2 is two independent exhaustive searches for a tiling.
Exits 0 only if every check passes.
"""
import sys

ROWS, COLS, PIECES = 6, 10, 15
fails = []


def check(name, got, want):
    ok = got == want
    print(("ok  " if ok else "FAIL"), name, got, "" if ok else f"(want {want})")
    if not ok:
        fails.append(name)


# Area and counts
check("area 6 x 10", ROWS * COLS, 60)
check("area of 15 pieces", PIECES * 4, 60)
check("area alone allows it", (ROWS * COLS) % 4, 0)

# Colourings of the board, counted square by square
cells = [(r, c) for r in range(ROWS) for c in range(COLS)]
stripes = lambda r, c: c % 2          # alternate columns
rowstripes = lambda r, c: r % 2       # alternate rows
chess = lambda r, c: (r + c) % 2
for name, col in [("column stripes", stripes), ("row stripes", rowstripes), ("chessboard", chess)]:
    dark = sum(col(r, c) == 0 for r, c in cells)
    check(f"{name}: dark squares", dark, 30)
    check(f"{name}: light squares", ROWS * COLS - dark, 30)
# Second route for the stripes count: 5 dark columns of 6 squares
check("stripes: 5 columns x 6", (COLS // 2) * ROWS, 30)


# Orientations of the L, route A: generated by rotating and reflecting the base shape
def normalise(sh):
    mr = min(r for r, c in sh)
    mc = min(c for r, c in sh)
    return tuple(sorted((r - mr, c - mc) for r, c in sh))


base = [(0, 0), (1, 0), (2, 0), (2, 1)]
orients = set()
sh = base
for _ in range(4):
    sh = [(c, -r) for r, c in sh]
    orients.add(normalise(sh))
    orients.add(normalise([(r, -c) for r, c in sh]))
orients = sorted(orients)
check("orientations of an L", len(orients), 8)

# Route B: the 8 orientations written out by hand
hand = {
    ((0, 0), (1, 0), (2, 0), (2, 1)), ((0, 1), (1, 1), (2, 0), (2, 1)),
    ((0, 0), (0, 1), (1, 0), (2, 0)), ((0, 0), (0, 1), (1, 1), (2, 1)),
    ((0, 0), (0, 1), (0, 2), (1, 0)), ((0, 0), (0, 1), (0, 2), (1, 2)),
    ((0, 0), (1, 0), (1, 1), (1, 2)), ((0, 2), (1, 0), (1, 1), (1, 2)),
}
check("hand list equals generated list", set(orients) == hand, True)

# Every placement on the board
placements = []
for o in orients:
    h = max(r for r, c in o) + 1
    w = max(c for r, c in o) + 1
    for r0 in range(ROWS - h + 1):
        for c0 in range(COLS - w + 1):
            placements.append(tuple((r0 + r, c0 + c) for r, c in o))
check("placements on 6 x 10", len(placements), 4 * (ROWS - 1) * (COLS - 2) + 4 * (ROWS - 2) * (COLS - 1))

split = lambda p, col: tuple(sorted((sum(col(r, c) == 0 for r, c in p), sum(col(r, c) == 1 for r, c in p))))
check("every placement covers 3 and 1 of the column stripes",
      {split(p, stripes) for p in placements}, {(1, 3)})
check("every placement covers 3 and 1 of the row stripes",
      {split(p, rowstripes) for p in placements}, {(1, 3)})
check("every placement covers 2 and 2 of the chessboard",
      {split(p, chess) for p in placements}, {(2, 2)})
# Case reason: line of three in one column gives 3 in that column, 1 beside;
# line of three across three columns has ends in columns c and c+2, one colour.
for o in orients:
    colsused = sorted(c for r, c in o)
    if max(colsused) == 1:   # 2 wide: line of three is vertical
        check(f"vertical L {o}: 3 in one column", max(colsused.count(0), colsused.count(1)), 3)
    else:                     # 3 wide: ends share a colour, extra square at an end
        check(f"flat L {o}: columns 0 and 2 hold 3", colsused.count(0) + colsused.count(2), 3)

# The count: a pieces add +2 to dark minus light, 15 - a add -2
totals = {4 * a - 30 for a in range(PIECES + 1)}
check("4a - 30 is never 0 for a = 0..15", 0 in totals, False)
check("totals, route 2: sum of 15 odd steps is odd",
      all(((2 * a - 2 * (PIECES - a)) // 2) % 2 == 1 for a in range(PIECES + 1)), True)
check("4a - 30 mod 4", {t % 4 for t in totals}, {2})
check("smallest |4a - 30|", min(abs(t) for t in totals), 2)
check("a giving +-2", [a for a in range(PIECES + 1) if abs(4 * a - 30) == 2], [7, 8])
check("dark columns, 1-indexed", [c + 1 for c in range(COLS) if stripes(0, c) == 0], [1, 3, 5, 7, 9])


# Exhaustive search A: bitmask, row-major, placements from the generated orientations
def count_a(R, C):
    pl = {}
    for o in orients:
        h = max(r for r, c in o) + 1
        w = max(c for r, c in o) + 1
        for r0 in range(R - h + 1):
            for c0 in range(C - w + 1):
                sq = [(r0 + r) * C + c0 + c for r, c in o]
                pl.setdefault(min(sq), []).append(sum(1 << s for s in sq))
    full = (1 << (R * C)) - 1
    memo = {}

    def go(mask):
        if mask == full:
            return 1
        if mask in memo:
            return memo[mask]
        f = (~mask & (mask + 1)).bit_length() - 1
        n = sum(go(mask | m) for m in pl.get(f, []) if not mask & m)
        memo[mask] = n
        return n
    return go(0)


# Exhaustive search B: sets, column-major first empty, hand-written orientations
def count_b(R, C):
    order = [(r, c) for c in range(C) for r in range(R)]

    def go(filled):
        for cell in order:
            if cell not in filled:
                break
        else:
            return 1
        n = 0
        for o in hand:
            for ar, ac in o:   # put each square of the shape on the empty cell
                p = [(cell[0] + r - ar, cell[1] + c - ac) for r, c in o]
                if all(0 <= r < R and 0 <= c < C and (r, c) not in filled for r, c in p):
                    # the empty cell must be first in column-major order
                    if min(p, key=lambda x: (x[1], x[0])) == cell:
                        n += go(filled | set(p))
        return n
    return go(frozenset())


for R, C, want in [(2, 4, 2), (4, 4, 10), (3, 8, 4), (6, 6, 0), (6, 10, 0)]:
    a = count_a(R, C)
    check(f"search A tilings of {R} x {C}", a, want)
    if R * C <= 36:
        check(f"search B tilings of {R} x {C}", count_b(R, C), a)
print("search B on 6 x 10 (slow route) ...")
check("search B tilings of 6 x 10", count_b(6, 10), 0)

if fails:
    print(len(fails), "checks failed")
    sys.exit(1)
print("all checks passed")
