def b_validate(args, schema):
    if type(args) is not dict:
        return ['arguments must be an object']
    out, props = [], schema.get('properties', {})
    out += [f"missing required field '{r}'" for r in schema.get('required', []) if r not in args]
    names = {str: 'string', bool: 'boolean', int: 'integer', float: 'number', list: 'array', dict: 'object', type(None): 'null'}
    for k, v in args.items():
        if k not in props:
            if schema.get('additionalProperties') is False:
                out.append(f"unexpected field '{k}'")
            continue
        p, t = props[k], props[k].get('type')
        good = (t == 'string' and type(v) is str) or (t == 'integer' and type(v) is int) or (t == 'number' and type(v) in (int, float)) or (t == 'boolean' and type(v) is bool) or t not in ('string', 'integer', 'number', 'boolean')
        if not good:
            out.append(f"field '{k}' must be {t}, got {names[type(v)]}")
            continue
        if 'enum' in p and v not in p['enum']:
            out.append(f"field '{k}' must be one of {', '.join(map(str, p['enum']))}")
        if 'minimum' in p and v < p['minimum']:
            out.append(f"field '{k}' must be at least {p['minimum']}")
        if 'maximum' in p and v > p['maximum']:
            out.append(f"field '{k}' must be at most {p['maximum']}")
    return out


def b_step(reply, tools, poor=False):
    n = reply['name']
    if n not in tools:
        e = f"unknown tool '{n}'; available: {', '.join(sorted(tools))}"
    else:
        try:
            a = json.loads(reply['arguments'])
            errs = b_validate(a, tools[n]['schema'])
            if errs:
                e = '; '.join(errs)
            else:
                try:
                    return {'result': tools[n]['fn'](**a)}
                except Exception as x:
                    e = f'{n} failed: {x}'
        except json.JSONDecodeError as x:
            e = f'arguments are not valid JSON: {x.msg}'
    return {'error': 'invalid input' if poor else e}


def b_run(task, tools, cap, poor=False, repeat=True):
    specs = [{'name': n, 'description': t['description'], 'input_schema': t['schema']} for n, t in tools.items()]
    msgs = [{'role': 'user', 'content': f"[{task['id']}] {task['question']}"}]
    calls = []
    for _ in range(cap):
        r = o3.respond(msgs, specs)
        msgs.append({'role': 'assistant', 'content': r})
        if r['type'] == 'answer':
            return {'status': 'answer', 'answer': r['text'], 'messages': msgs}
        msgs.append({'role': 'tool', 'name': r['name'], 'content': b_step(r, tools, poor)})
        calls.append(json.dumps([r['name'], r['arguments']]))
        if repeat and len(calls) >= 3 and calls[-1] == calls[-2] == calls[-3]:
            return {'status': 'repeated', 'answer': None, 'messages': msgs}
    return {'status': 'max_steps', 'answer': None, 'messages': msgs}


def b_score(tr, task):
    ok = {m['name'] for m in tr['messages'] if m['role'] == 'tool' and 'result' in m['content']}
    c = tr['answer'] is not None and tr['answer'].strip() == task['answer']
    u = set(task['required']) <= ok
    return {'correct': c, 'used_required': u, 'success': c and u}


def b_lines(tr):
    out = [f"user: {tr['messages'][0]['content']}"]
    for m in tr['messages'][1:]:
        c = m['content']
        if m['role'] == 'assistant':
            out.append(f"model: call {c['name']} {c['arguments']}" if c['type'] == 'tool_call' else f"model: answer {c['text']}")
        else:
            out.append(f"tool: {json.dumps(c)}")
    return out


