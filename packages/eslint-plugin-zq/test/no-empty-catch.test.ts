import rule from '../src/rules/no-empty-catch.ts';
import { tester } from './tester.ts';

const swallowed = [{ messageId: 'swallowed' }];
const fails = (code: string) => ({ code, errors: swallowed });

tester.run('no-empty-catch', rule, {
  valid: [
    'try { f() } catch (e) { throw e }',
    'try { f() } catch { throw new Error("failed") }',
    'try { f() } catch { if (retry) { throw new Error("failed") } }',
    'try { f() } catch { log.warn("failed") }',
    'try { f() } catch { console.error("failed") }',
    'try { f() } catch { this.logger.info("failed") }',
    'try { f() } catch { (log as Logger).warn("failed") }',
    'try { f() } catch (e) { return e }',
    'try { f() } catch (e) { setTimeout(() => report(e)) }',
    'try { f() } catch ({ message }) { show(message) }',
    'try { f() } catch (e: unknown) { reject(e as Error) }',
    'try { f() } catch (e) { done(e!) }',
    'try { f() } catch (e) { report(String(e)) }',
    'try { f() } catch (e) { notify("failed: " + e.message) }',
    'try { f() } catch (e) { notify(`failed: ${e}`) }',
    'try { f() } catch (e) { tag`failed: ${e}` }',
    'try { f() } catch (e) { return { ok: false, error: e } }',
    'try { f() } catch (e) { errors.push([e]) }',
    'try { f() } catch (e) { return ready ? e : null }',
    'try { f() } catch (e) { const view = <Failure error={e} /> }',
    'let failure; try { f() } catch (e) { failure = e }',
    'try { f() } catch (e) { const message = describe(e); setError(message) }',
    'try { f() } catch (e) { const text = String(e); show(text) }',
    'try { f() } catch (e) { const copy = e; report(copy) }',
    'try { f() } catch (e) { const message = e.message; return message }',
    'try { f() } catch (e) { this.error = e }',
    'try { f() } catch (e) { state.error = e }',
    'function* g() { try { f() } catch (e) { yield e } }',
    'try { a() } catch (e) { try { b() } catch { throw e } }',
    'try { a() } catch { try { b() } catch { throw new Error("both failed") } }',
    'p.catch((e) => e)',
    'p.catch((e) => { report(e) })',
    'p.catch(() => log.error("failed"))',
    'p.catch(() => { throw new Error("failed") })',
    'p.catch(function (e) { report(e) })',
    'p["catch"](({ code }) => code)',
    'p.catch((e) => String(e))',
    'p.then(ok, (e) => e)',
    'p.then(ok)',
    'p.then((v) => v, undefined)',
    'p.catch(handle)',
    'p?.catch((e) => e)',
    'import { onError } from "./errors.ts"; p.catch(onError)',
    'const onError = (e) => report(e); p.catch(onError)',
    'p.catch(onError); function onError(e) { log.warn(e) }',
    'let onError = () => {}; p.catch(onError)',
    'p.catch(((e) => e) as Handler)',
    'p.catch(((e) => e) satisfies Handler)',
    { code: 'try { f() } catch { audit.warn("failed") }', options: [{ loggers: ['audit'] }] },
  ],
  invalid: [
    fails('try { f() } catch {}'),
    fails('(p?.catch)(() => {})'),
    fails('p.catch!(() => {})'),
    fails('(p?.then)(ok, () => {})'),
    fails('(p.catch as C)(() => {})'),
    fails('try { f() } catch (e) {}'),
    fails('try { f() } catch (e) { /* ignored */ }'),
    fails('try { f() } catch (e) { e = null }'),
    fails('try { f() } catch (e) { if (e) {} }'),
    fails('try { f() } catch (e) { String(e); }'),
    fails('try { f() } catch (e) { void String(e); }'),
    fails('try { f() } catch (e) { e satisfies unknown; }'),
    fails('try { f() } catch (e) { e.message }'),
    fails('try { f() } catch (e) { typeof e }'),
    fails('try { f() } catch (e) { seen[e] = true }'),
    fails('try { f() } catch (e) { const copy = e }'),
    fails('try { f() } catch (e) { const box = { e } }'),
    fails('try { f() } catch (e) { let local; local = e }'),
    fails('try { f() } catch (e) { const a = e; const b = a; report(b) }'),
    fails('try { f() } catch (e) { let copy = e; report(copy) }'),
    fails('try { f() } catch (e) { const text = String(e); text.length }'),
    fails('try { f() } catch { function g() { throw new Error("later") } }'),
    fails('try { f() } catch { metrics.warn("failed") }'),
    fails('try { f() } catch { log.debug("failed") }'),
    {
      code: 'try { f() } catch { console.warn("failed") }',
      options: [{ loggers: ['log'] }],
      errors: swallowed,
    },
    fails('try { f() } catch (e) { const g = (e) => e }'),
    fails('try { f() } catch { p.catch(() => { log.warn("inner") }) }'),
    fails('p.catch(() => {})'),
    fails('p.catch(() => undefined)'),
    fails('p.catch((_e) => {})'),
    fails('p.catch(async () => {})'),
    fails('p.catch(function named() {})'),
    fails('p.catch((a, b) => b)'),
    fails('p.catch(() => { const g = () => { throw new Error("later") } })'),
    fails('p.then(ok, () => {})'),
    fails('p.catch((() => {}) as Handler)'),
    fails('p.catch((() => {})!)'),
    fails('const ignore = () => {}; p.catch(ignore)'),
    fails('const ignore = (_e) => undefined; p.then(ok, ignore)'),
    fails('p.catch(ignore); function ignore() {}'),
  ],
});
