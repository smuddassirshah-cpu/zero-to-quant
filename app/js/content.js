/* Content loader and registry (docs/PLAN.md section 5). At start it fetches content/curriculum.json, then every
   course.json it lists, in parallel; ZQ.content.ready resolves when both are in. Lessons, reviews, homework, exams and
   drills and the question bank are fetched on demand and cached. content/manifest.json (written by tools/validate.mjs) lists every authored
   file, so a lesson that is not written yet is known as missing without a request; without a manifest, a 404 is
   cached as missing, never thrown. Course art ids are the kinds in js/art.js (ZQArt.kinds). content/prep.json (prep paths, ENGINE-BACKLOG 455) is read at start too,
   only when the manifest lists it. */
(function () {
  'use strict';
  const BASE = 'content/';
  let curriculum = null;          // curriculum.json as loaded
  const courseDocs = {};          // course id -> course.json (or null when it failed to load)
  let manifest = null;            // Set of paths relative to content/, or null when there is no manifest
  const samples = new Set();      // the manifest's sample files ("sample": true), hidden from every list
  const cache = new Map();        // path -> Promise<object|null>
  const known = new Map();        // path -> true (found) | false (missing)
  let drillIndex = null;
  let examMins = null;            // manifest.examMinutes: exam id -> minutes the exam screen runs (ENGINE-BACKLOG 621); null without it
  let selfExams = null;           // manifest.selfExams: exam ids holding a longform item or a check part; null without a manifest
  let perfTasks = {};             // manifest.perf: "course/L<n>" -> { file, item, kind, how }, the levels that carry a performance task (ENGINE-BACKLOG 529)
  let drillMeta = {};             // manifest.drills: id -> { language, pattern, pace, tags, sample } read from each drill file (engine pass C, item 472)
  let lessonMins = {}, setMins = {};   // manifest.lessonMinutes ("course/lesson" -> minutes) and manifest.setMinutes ("course/review-1" -> minutes, only where the file states it): the in-app hours (js/hours.js)
  let sessions = {};              // manifest.sessions: "course/lesson" -> { session, minutes } for workshop and project lessons (item 10)
  let fluencyMeta = {};           // manifest.fluency: "course/set-id" -> { lesson, title, n, pass, minutes, families } for generated fluency sets (ENGINE-BACKLOG 804)
  const fluencyDocs = new Map();  // "course/set-id" -> a set document registered by a test hook (tools/fixtures; never a content file)
  let hoursModel = null;          // ZQ.hours.build over the curriculum, course maps, manifest and sessions (item 11); null until content is ready
  let capstoneDoc = [];           // content/capstones.json: one record per role (ENGINE-BACKLOG 564), [] when the file is absent
  let readinessDoc = null;        // content/readiness.json (generated by tools/readiness-sums.mjs --write), or null
  let prepDoc = null;             // content/prep.json (ENGINE-BACKLOG 455), or null when there is none

  const deKebab = (id) => {
    const s = String(id).replace(/^l\d+-/, '').replace(/-/g, ' ');
    return s.charAt(0).toUpperCase() + s.slice(1);
  };
  const getJSON = async (path, { optional = false } = {}) => {
    const res = await fetch(BASE + path, { cache: 'no-cache' });
    if (res.status === 404 && optional) return null;
    if (!res.ok) throw new Error(`content/${path}: HTTP ${res.status}`);
    try { return await res.json(); } catch (e) { throw new Error(`content/${path}: ${e.message}`); }
  };
  /* Fetch once and cache. Missing files resolve to null; malformed files reject (and are logged once). */
  const load = (path) => {
    if (cache.has(path)) return cache.get(path);
    let p;
    if (manifest && !manifest.has(path)) { known.set(path, false); p = Promise.resolve(null); }
    else {
      p = getJSON(path, { optional: true }).then(d => { known.set(path, d != null); return d; })
        .catch(e => { console.error(e); known.set(path, false); cache.delete(path); throw e; });
    }
    cache.set(path, p);
    return p;
  };

  /* ---------- Registry over the curriculum ---------- */
  /* Strands: a course.json may carry strand ("quant" or "pure") and strandNote (the roles). The "Quant path only"
     setting hides pure courses and the topics that hold only pure courses from stages() and courses(); topic(),
     course() and stage() still find everything, so a link or a saved resume point to a pure course keeps working. */
  const quantOnly = () => { try { const S = window.ZQ && window.ZQ.state; return !!(S && S.settings && S.settings.quantOnly); } catch { return false; } };
  const isPure = (id) => { const m = (curriculum && curriculum.courses[id]) || {}, d = courseDocs[id] || {}; return (d.strand || m.strand) === 'pure'; };
  const strandOfCourse = (id) => { const m = (curriculum && curriculum.courses[id]) || {}, d = courseDocs[id] || {}; const v = d.strand || m.strand; return v === 'pure' || v === 'quant' ? v : null; };
  /* A topic has a strand when every one of its courses carries the same one; mixed or untagged topics have none */
  const topicStrand = (t) => {
    const ids = (t && t.courses) || [];
    const set = new Set(ids.map(id => strandOfCourse(id) || ''));
    return set.size === 1 && ids.length && [...set][0] ? [...set][0] : null;
  };
  const strandNoteOf = (ids) => {
    const notes = [...new Set((ids || []).map(id => (courseDocs[id] || {}).strandNote).filter(Boolean))];
    return notes.join(' ');
  };
  const STRAND_NAME = { pure: 'Pure maths', quant: 'Quant' };
  const escAttr = (v) => String(v).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
  /* The badge markup for a strand with its note as the tooltip and the screen-reader detail; '' for no strand */
  const strandBadge = (strand, note = '', cls = '') => {
    if (!STRAND_NAME[strand]) return '';
    const n = escAttr(note || (strand === 'pure' ? 'Pure maths: not needed to be hired.' : 'Quant path: used in quant roles.'));
    return `<span class="strand-badge is-${strand}${cls ? ' ' + cls : ''}" title="${n}" aria-label="${STRAND_NAME[strand]}. ${n}">${STRAND_NAME[strand]}</span>`;
  };
  const allStages = () => (curriculum ? curriculum.stages : []);
  const stages = () => {
    const all = allStages();
    if (!quantOnly()) return all;
    return all.map(s => ({
      ...s,
      topics: s.topics.flatMap(t => {
        const cs = t.courses || [], kept = cs.filter(id => !isPure(id));
        if (cs.length && !kept.length) return [];
        return [kept.length === cs.length ? t : { ...t, courses: kept }];
      }),
    }));
  };
  const stage = (n) => allStages().find(s => s.id === Number(n)) || null;
  const topic = (id) => { for (const s of allStages()) for (const t of s.topics) if (t.id === String(id)) return { ...t, stage: s.id }; return null; };
  const topicOfCourse = (cid) => { for (const s of allStages()) for (const t of s.topics) if ((t.courses || []).includes(cid)) return { s, t }; return null; };
  /* Tested out: a passed topic exam, read from the saved attempts at call time (nothing stored per lesson).
     Today and the "up next" course skip a course whose topic is passed; lesson flags and progress are untouched. */
  /* The pass that counts (provenance, N01): an attempt counts when passed and its auto part passed. passedAuto is stored at finish.
     An old attempt has none: it counts as `passed` for an exam the manifest says holds no self item or check, and not at all
     for an exam that does, or when there is no manifest. This is the one rule; prereq, Today and Learn all read it. */
  const autoPasses = (id) => {
    try {
      const r = window.ZQ.state.exams[id];
      const old = !!selfExams && !selfExams.has(id);
      return r && Array.isArray(r.attempts) ? r.attempts.filter(a => a && a.passed && (typeof a.passedAuto === 'boolean' ? a.passedAuto : old)) : [];
    } catch { return []; }
  };
  const examPassedAuto = (id) => autoPasses(id).length > 0;
  const examAutoAttempts = (id) => autoPasses(id);   // the attempts that count as a pass; met rule 4 reads their bySkillAuto
  const examPassedAt = (id) => autoPasses(id).reduce((m, a) => Math.max(m, Number(a.at) || 0), 0);
  /* the performance task of a level, or null (a level the manifest does not list has none, and so does an app with no manifest) */
  const perfOf = (cid, n) => perfTasks[`${cid}/L${n}`] || null;
  const setPerf = (m) => { perfTasks = m && typeof m === 'object' ? m : {}; };   // test hook, like state._setClock
  const topicPassed = (tid) => examPassedAuto('topic-' + tid);
  const courseTestedOut = (cid) => { const w = topicOfCourse(cid); return !!w && topicPassed(w.t.id); };
  /* A saved lesson position in a tested-out course pins "where you are" only if the learner opened that lesson on purpose from Learn or the
     course map after the passing attempt (pickedAt, ENGINE-BACKLOG 617). The save time does not count: leaving a lesson, Back or a reload
     re-saves it, and a record from before pickedAt existed has none, so it is skipped. Record: state.summary().resume: { course, lesson, at, pickedAt }. */
  const resumeStands = (r) => {
    if (!r || !courseTestedOut(r.course)) return !!r;
    try {
      const w = topicOfCourse(r.course), at = examPassedAt('topic-' + w.t.id);
      return (Number(r.pickedAt) || 0) > at;
    } catch { return false; }
  };
  const course = (id) => {
    if (!curriculum || !curriculum.courses[id]) return null;
    const meta = curriculum.courses[id], doc = courseDocs[id] || {};
    const where = topicOfCourse(id);
    return {
      id, ...meta, ...doc,
      name: doc.name || meta.name, art: doc.art || meta.art, description: doc.description || meta.description,
      topic: (where && where.t.id) || meta.topic, topicName: where ? where.t.name : '', stage: where ? where.s.id : null, track: where ? where.t.track : null,
      skills: doc.skills || {}, levels: doc.levels || [], loaded: !!courseDocs[id],
      strand: strandOfCourse(id), strandNote: strandOfCourse(id) ? (doc.strandNote || '') : '',
    };
  };
  const allCourses = () => allStages().flatMap(s => s.topics.flatMap(t => (t.courses || []).map(id => course(id)).filter(Boolean)));
  const courses = () => (quantOnly() ? allCourses().filter(c => c.strand !== 'pure') : allCourses());

  /* Ordered list of everything on a course map: each level's lessons, then its review, then its homework */
  const lessonCache = new Map();  // `${course}/${id}` -> loaded lesson title, for names when the map has none
  const nameOf = (doc, id) => (doc.lessonNames && doc.lessonNames[id]) || lessonCache.get(`${doc.id}/${id}`) || deKebab(id);
  const courseLessons = (id) => {
    const doc = courseDocs[id];
    if (!doc || !Array.isArray(doc.levels)) return [];
    const out = [];
    doc.levels.forEach(lv => {
      (lv.lessons || []).forEach(l => out.push({ level: lv.n, id: l, kind: 'lesson', name: nameOf(doc, l), objective: (doc.lessonObjectives || {})[l] || '', written: exists(id, l) }));
      if (lv.review) out.push({ level: lv.n, id: lv.review, kind: 'review', name: 'Level review', written: exists(id, lv.review) });
      if (lv.homework) out.push({ level: lv.n, id: lv.homework, kind: 'homework', name: `Homework ${lv.n}`, written: exists(id, lv.homework) });
    });
    return out;
  };
  const next = (cid, afterId) => {
    const list = courseLessons(cid);
    const i = list.findIndex(x => x.id === afterId);
    return i >= 0 && i + 1 < list.length ? list[i + 1] : null;
  };
  /* true: the file is there; false: it is not written yet; null: not known yet (no manifest, never fetched) */
  const exists = (cid, id) => {
    const path = `courses/${cid}/${id}.json`;
    if (known.has(path)) return known.get(path);
    if (manifest) return manifest.has(path);
    return null;
  };

  const lesson = (cid, id) => load(`courses/${cid}/${id}.json`).then(d => { if (d && d.title) lessonCache.set(`${cid}/${id}`, d.title); return d; });
  /* The skills tagged on a review's items (the level's essential skills, met rules 2 and 4), kept as reviews load so the met rule can read them without waiting */
  const essentials = new Map();   // `${cid}/${reviewId}` -> [skill]
  const review = (cid, id) => load(`courses/${cid}/${id}.json`).then(d => { if (d && Array.isArray(d.items)) essentials.set(`${cid}/${id}`, [...new Set(d.items.flatMap(it => it.skills || []).filter(Boolean))]); return d; });
  const essentialSkills = (cid, id) => essentials.get(`${cid}/${id}`) || null;
  const loadEssentials = (cid) => Promise.all(((courseDocs[cid] || {}).levels || []).filter(l => l.review && exists(cid, l.review) !== false).map(l => review(cid, l.review).catch(() => null)));
  const homework = (cid, id) => load(`courses/${cid}/${id}.json`);
  /* true or false from the manifest; null when there is no manifest */
  const examWritten = (id) => (manifest ? manifest.has(`exams/${id}.json`) : null);
  const exam = (id) => load(`exams/${id}.json`);
  /* Minutes the exam screen runs for an exam id (the one value every screen shows), or null when the manifest does not say */
  const examMinutes = (id) => (examMins && typeof examMins[id] === 'number' ? examMins[id] : null);
  /* The mock assessments written (exams/mock-*.json in the manifest), sorted by id; empty while there is no manifest */
  const mocks = () => (manifest ? [...manifest].filter(f => /^exams\/mock-[^/]+\.json$/.test(f) && !samples.has(f)).map(f => f.slice(6, -5)).sort() : []);
  /* The interview question bank (content/bank/<family>.json, ENGINE-BACKLOG 456): file ids from the manifest, sorted; none without one */
  const bankIds = () => (manifest ? [...manifest].filter(f => /^bank\/[^/]+\.json$/.test(f) && !samples.has(f)).map(f => f.slice(5, -5)).sort() : []);
  const bank = (id) => load(`bank/${id}.json`);
  /* ENGINE-BACKLOG 469 (E14): data files for Python code items. map is { "bare-name.csv": "content/data/<path>" }; resolves to
     { "bare-name.csv": "<text>" }. Each path is fetched once and cached; a file that cannot be read rejects with a plain message. */
  const dataCache = new Map();
  const dataFiles = (map) => {
    const names = map && typeof map === 'object' ? Object.keys(map) : [];
    return Promise.all(names.map(n => {
      const p = String(map[n]);
      if (!dataCache.has(p)) dataCache.set(p, fetch(new URL(p, document.baseURI).href, { cache: 'no-cache' }).then(r => { if (!r.ok) throw new Error(`${p}: HTTP ${r.status}`); return r.text(); }).catch(e => { dataCache.delete(p); throw e; }));
      return dataCache.get(p).then(t => [n, t]);
    })).then(Object.fromEntries);
  };
  const drill = (id) => load(`drills/${id}.json`);
  /* Verified-oa-drill rule (ENGINE-BACKLOG 568): an oa drill (pack "oa", or an id starting "oa-") maps to the level named by its `level` field
     (index row or drill file), else to the lowest level of its `course` that carries a gating code performance task. Returns the drill ids for one level. */
  const perfDrillsFor = (cid, n) => {
    const lowest = () => { const co = course(cid); const lv = ((co && co.levels) || []).find(l => { const t = perfOf(cid, l.n); return t && t.gates && t.kind === 'code'; }); return lv ? lv.n : null; };
    let dflt;
    return drills().filter(d => d && d.course === cid && (d.pack === 'oa' || String(d.id).startsWith('oa-'))).filter(d => {
      const L = Number.isInteger(d.level) ? d.level : (dflt === undefined ? (dflt = lowest()) : dflt);
      return L === n;
    }).map(d => d.id);
  };
  /* The listed drills, each row with what the drill file says (language, pattern, tags, pace) from the manifest, so a
     filter never fetches 100 files. A file's own value wins over the index row. */
  const drills = () => (drillIndex || []).filter(d => !samples.has(`drills/${typeof d === 'string' ? d : d && d.id}.json`)).map(r => { const m = drillMeta[r && r.id]; return m ? { ...r, ...m } : r; });
  /* Fixed drill sessions (content/drills/sessions/<id>.json, item 472): ids from the manifest, sorted; none without one */
  const drillSessionIds = () => (manifest ? [...manifest].filter(f => /^drills\/sessions\/[^/]+\.json$/.test(f)).map(f => f.slice(15, -5)).sort() : []);
  const drillSession = (id) => load(`drills/sessions/${id}.json`);
  /* Samples (ENGINE-BACKLOG 467, 468): a file with a top-level "sample": true is listed under `samples` in the manifest. It loads
     by its route or id as any file does, but mocks(), bankIds(), drills(), the bank deck and every count leave it out. */
  const isSample = (path) => samples.has(path);
  /* The manifest's files under a folder prefix ("bank/", "drills/"), sorted; samples only when asked (a sample exam drawing from sample files) */
  const fileList = (prefix, { sample = false } = {}) => (manifest ? [...manifest].filter(f => f.startsWith(prefix) && f.endsWith('.json') && !f.slice(prefix.length).includes('/') && (sample || !samples.has(f))).sort() : []);

  /* ---------- Prep paths (content/prep.json, ENGINE-BACKLOG 455, docs/AUTHORING.md section 10) ----------
     Which lessons prepare for which assessment. Paths never unlock or gate anything; they only label lessons and list
     them in study order on the Prepare for page (js/screens/prepare.js). A step's ref is a course id, <course>/level-<n>
     or <course>/<lesson-id>; it expands to lessons listed in course.json, written or not. */
  const MONTH_NAMES = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
  /* "2026-10" or "2026-10-15" -> "October 2026"; '' when it does not parse */
  const prepMonth = (asOf) => { const m = /^(\d{4})-(\d{2})/.exec(String(asOf || '')); return m && +m[2] >= 1 && +m[2] <= 12 ? `${MONTH_NAMES[+m[2] - 1]} ${m[1]}` : ''; };
  const STAGE_NAME = { oa: 'OA', interview: 'interview', superday: 'superday' };
  const STAGE_LABEL = { oa: 'OA', interview: 'Interview', superday: 'Superday' };
  /* Item 10: the session of a lesson ({ session: 'workshop' | 'project', minutes }) or null for a short one; the line a course card shows for the workshops it holds */
  const sessionOf = (cid, id) => sessions[`${cid}/${id}`] || null;
  const courseSessionLabel = (cid) => {
    const H = window.ZQ && window.ZQ.hours, d = courseDocs[cid];
    if (!H || !d) return '';
    return H.courseSessionLabel((d.levels || []).flatMap(lv => (lv.lessons || []).map(l => sessionOf(cid, l))));
  };

  /* ---------- Readiness contract (content/readiness.json, docs/readiness.md, docs/AUTHORING.md section 12) ----------
     A profile track maps to a contract role key; Undecided and an unknown track read as 'undecided'. Course status for a role:
     'required', 'recommended' or 'optional'; null when there is no readiness file. */
  const ROLE_OF_TRACK = { Trader: 'trader', Researcher: 'researcher', Developer: 'developer', Strats: 'strats', Undecided: 'undecided' };
  const roleKey = (track) => ROLE_OF_TRACK[track] || 'undecided';
  const roleStatus = (cid, role) => { const r = readinessDoc && readinessDoc.roles[role]; return r && r.courses ? r.courses[cid] || null : null; };
  const readiness = {
    get doc() { return readinessDoc; }, roleKey, status: roleStatus,
    totals: (role) => { const r = readinessDoc && readinessDoc.roles[role]; return r ? r.totals : null; },
    /* Next work for a track: required courses first, then recommended, never optional. Undecided, or no readiness file, leaves the list as it is. */
    offerable: (cid, track) => { const r = roleKey(track); return !readinessDoc || r === 'undecided' || roleStatus(cid, r) !== 'optional'; },
    plan: (list, track) => {
      const r = roleKey(track);
      if (!readinessDoc || r === 'undecided') return list;
      const rank = (c) => (roleStatus(c.id, r) === 'required' ? 0 : roleStatus(c.id, r) === 'recommended' ? 1 : 2);
      return list.filter(c => rank(c) < 2).map((c, i) => ({ c, i })).sort((a, b) => rank(a.c) - rank(b.c) || a.i - b.i).map(x => x.c);
    },
    limited: (cid) => (readinessDoc && readinessDoc.limited && readinessDoc.limited[cid]) || '',
    /* Capstone records (ENGINE-BACKLOG 564): capstone(role) is the record or null; capstoneComplete(rec) is the one rule for "done". */
    capstones: () => capstoneDoc.slice(),
    capstone: (role) => capstoneDoc.find(r => r.role === role) || null,
    capstoneComplete: (r) => capstoneComplete(r),
    /* Role status: { role, levels: { total, met, missing: [{course, n}] }, capstone: record|null, capstoneDone, ready, missing: [text] }.
       Ready only when every level of the role's required courses is met and a complete external capstone record exists. */
    roleState: (role) => {
      const P = window.ZQ && window.ZQ.prereq, r = readinessDoc && readinessDoc.roles[role];
      const levels = { total: 0, met: 0, missing: [] };
      if (r && r.courses && P) Object.keys(r.courses).filter(c => r.courses[c] === 'required').forEach(cid => {
        const co = course(cid); ((co && co.levels) || []).forEach(lv => { levels.total++; let m = false; try { m = P.levelMet(cid, lv.n); } catch { m = false; } if (m) levels.met++; else levels.missing.push({ course: cid, n: lv.n }); });
      });
      const rec = capstoneDoc.find(x => x.role === role) || null, done = capstoneComplete(rec);
      const missing = [];
      if (!r || role === 'undecided') missing.push('No role chosen');
      else if (levels.met < levels.total) missing.push(`${levels.total - levels.met} required levels not met`);
      if (role !== 'undecided' && !done) missing.push(rec && (rec.external || rec.repo || rec.reviewer || rec.date || rec.project) ? 'Capstone incomplete' : 'Capstone not recorded');
      return { role, levels, capstone: rec, capstoneDone: done, ready: !missing.length, missing };
    },
    /* The word "ready" as a role verdict comes only from here. */
    verdict: (role) => { const s = readiness.roleState(role); return s.ready ? 'Ready' : s.missing[0] === 'No role chosen' ? '' : `Not ready: ${s.missing.join('; ').toLowerCase()}`; },
  };
  /* A record counts only when external is true and repo, reviewer, date are non-empty and the rerun result is pass. */
  function capstoneComplete(r) { return !!r && r.external === true && ['repo', 'reviewer', 'date'].every(k => typeof r[k] === 'string' && r[k].trim()) && r.rerun === 'pass'; }
  const prep = () => prepDoc || { asOf: '', paths: [] };
  const prepPaths = () => prep().paths;
  const prepPath = (id) => prepPaths().find(p => p.id === id) || null;
  /* A ref's lessons as [{ course, id, level, name, written }]; [] when the ref names nothing */
  const prepRefLessons = (ref) => {
    const [cid, rest] = String(ref).split('/');
    if (!curriculum || !curriculum.courses[cid] || !courseDocs[cid]) return [];
    const all = courseLessons(cid).filter(x => x.kind === 'lesson');
    const pick = rest == null ? all : /^level-\d+$/.test(rest) ? all.filter(x => x.level === +rest.slice(6)) : all.filter(x => x.id === rest);
    return pick.map(x => ({ course: cid, id: x.id, level: x.level, name: x.name, written: x.written }));
  };
  /* The steps of a path with their lessons: [{ ...step, lessons }] */
  const prepSteps = (p) => ((typeof p === 'string' ? prepPath(p) : p) || { steps: [] }).steps.map(st => ({ ...st, lessons: prepRefLessons(st.ref) }));
  let prepIndex = null;           // `${course}/${lesson}` -> [path], built once, after the courses have loaded
  const prepIdx = () => {
    if (prepIndex) return prepIndex;
    prepIndex = new Map();
    prepPaths().forEach(p => p.steps.forEach(st => prepRefLessons(st.ref).forEach(l => {
      const k = `${l.course}/${l.id}`, a = prepIndex.get(k) || [];
      if (!a.includes(p)) a.push(p);
      prepIndex.set(k, a);
    })));
    return prepIndex;
  };
  const prepFor = (cid, lid) => prepIdx().get(`${cid}/${lid}`) || [];
  /* Every path that holds at least one lesson of the course */
  const prepForCourse = (cid) => {
    const out = [];
    prepIdx().forEach((a, k) => { if (k.startsWith(cid + '/')) a.forEach(p => { if (!out.includes(p)) out.push(p); }); });
    return prepPaths().filter(p => out.includes(p));
  };
  /* One plain line for a set of paths: "General, OA, superday. Optiver, SIG (reported, October 2026)." */
  const prepDetail = (paths) => {
    const out = [];
    const stages = [...(paths.some(p => p.kind === 'general') ? ['General'] : []), ...['oa', 'interview', 'superday'].filter(s => paths.some(p => p.kind === 'stage' && p.stage === s)).map(s => STAGE_NAME[s])];
    if (stages.length) out.push(stages.join(', '));
    const byMonth = new Map();
    paths.filter(p => p.kind === 'firm').forEach(p => { const m = prepMonth(p.asOf) || 'date not given'; byMonth.set(m, [...(byMonth.get(m) || []), p.name]); });
    byMonth.forEach((names, m) => out.push(`${names.join(', ')} (reported, ${m})`));
    return out.join('. ') + (out.length ? '.' : '');
  };
  /* The "Interview prep" chip; the title is the detail line */
  const prepChip = (paths, cls = '') => (paths && paths.length
    ? `<span class="prep-chip${cls ? ' ' + cls : ''}" title="${escAttr(prepDetail(paths))}">Interview prep</span>` : '');

  /* ---------- Start ---------- */
  const ready = (async () => {
    const [cur, man, di] = await Promise.all([
      getJSON('curriculum.json'),
      getJSON('manifest.json', { optional: true }).catch(e => { console.error(e); return null; }),
      getJSON('drills/index.json', { optional: true }).catch(e => { console.error(e); return null; }),
    ]);
    curriculum = cur;
    /* Item 11: a stage's hours are the sum of its topic hours (js/hours.js); a stored stage `hours` is ignored */
    const HRS = window.ZQ && window.ZQ.hours;
    if (HRS) (cur.stages || []).forEach(s => { s.hours = HRS.stageHours(s); });
    if (man && Array.isArray(man.files)) { manifest = new Set(man.files); manifest.forEach(f => known.set(f, true)); (Array.isArray(man.samples) ? man.samples : []).forEach(f => samples.add(f)); }
    if (man && man.examMinutes && typeof man.examMinutes === 'object') examMins = man.examMinutes;
    if (man && Array.isArray(man.selfExams)) selfExams = new Set(man.selfExams);
    if (man && man.perf && typeof man.perf === 'object') perfTasks = man.perf;
    if (man && man.sessions && typeof man.sessions === 'object') sessions = man.sessions;
    if (man && man.lessonMinutes && typeof man.lessonMinutes === 'object') lessonMins = man.lessonMinutes;
    if (man && man.setMinutes && typeof man.setMinutes === 'object') setMins = man.setMinutes;
    if (man && man.drills && typeof man.drills === 'object') drillMeta = man.drills;
    if (man && man.fluency && typeof man.fluency === 'object') fluencyMeta = man.fluency;
    drillIndex = Array.isArray(di) ? di : [];
    /* prep.json is requested only when the manifest lists it (or there is no manifest), so no 404 reaches the console */
    const pr = !manifest || manifest.has('prep.json') ? await getJSON('prep.json', { optional: true }).catch(e => { console.error(e); return null; }) : null;
    const rd = !manifest || manifest.has('readiness.json') ? await getJSON('readiness.json', { optional: true }).catch(e => { console.error(e); return null; }) : null;
    const cp = !manifest || manifest.has('capstones.json') ? await getJSON('capstones.json', { optional: true }).catch(e => { console.error(e); return null; }) : null;
    capstoneDoc = Array.isArray(cp) ? cp.filter(r => r && typeof r === 'object' && typeof r.role === 'string') : [];
    readinessDoc = rd && rd.roles && typeof rd.roles === 'object' ? rd : null;
    prepDoc = pr && Array.isArray(pr.paths) ? { asOf: pr.asOf || '', paths: pr.paths.filter(p => p && p.id && Array.isArray(p.steps)).map(p => ({ mocks: [], ...p })) } : null;
    const ids = Object.keys(cur.courses || {});
    await Promise.all(ids.map(id => getJSON(`courses/${id}/course.json`).then(d => { courseDocs[id] = d; })
      .catch(e => { console.error(e); courseDocs[id] = null; })));
    if (HRS) {
      hoursModel = HRS.build({ curriculum, courses: Object.fromEntries(Object.entries(courseDocs).filter(([, d]) => d)), written: (c, l) => exists(c, l) === true, sessions, minutes: (c, l) => lessonMins[`${c}/${l}`], setMinutes: setMins, examMinutes: examMins || {} });
      /* In-app and outside hours beside each stored figure (hoursApp, hoursOut): Learn and Setup show the two apart, never the stored total alone */
      (cur.stages || []).forEach(s => { s.hoursApp = hoursModel.stageApp(s.id); s.hoursOut = hoursModel.stageOut(s.id); (s.topics || []).forEach(t => { t.hoursApp = hoursModel.topicApp(t.id); t.hoursOut = hoursModel.topicOut(t.id); }); });
    }
    return api;
  })();
  ready.catch(e => console.error('Content failed to load:', e));

  const api = {
    ready,
    get curriculum() { return curriculum; },
    get tracks() { return (curriculum && curriculum.tracks) || {}; },
    stages, allStages, stage, topic, topicPassed, perfOf, _setPerf: setPerf, _setReadiness: (d) => { readinessDoc = d && d.roles ? d : null; }, _setCapstones: (a) => { capstoneDoc = Array.isArray(a) ? a : []; }, _setDrillMeta: (m) => { drillMeta = m && typeof m === 'object' ? m : {}; }, perfDrillsFor, examPassedAuto, examAutoAttempts, essentialSkills, loadEssentials, examPassedAt, courseTestedOut, resumeStands, course, courses, allCourses, topicStrand, strandNoteOf, strandBadge, quantOnly, courseLessons, next, exists,
    lesson, review, homework, exam, examMinutes, examWritten, mocks, bankIds, bank, drill, drills, dataFiles, drillSessionIds, drillSession, isSample, fileList,
    sessionOf, courseSessionLabel, get hours() { return hoursModel; },
    readiness, prep, prepPaths, prepPath, prepRefLessons, prepSteps, prepFor, prepForCourse, prepDetail, prepChip, prepMonth, prepStageLabel: (s) => STAGE_LABEL[s] || s,
    /* Resolves when every lesson, review and homework file of a course is known to exist or not */
    probe: (cid) => Promise.all(courseLessons(cid).map(x => load(`courses/${cid}/${x.id}.json`).catch(() => null))).then(() => courseLessons(cid)),
    deKebab,
  };
  /* Generated fluency sets (ENGINE-BACKLOG 804, docs/AUTHORING.md section 16): content/courses/<course>/fluency-<lesson>.json, found by file name and
     listed in the manifest under `fluency`. fluencyFor(course, lesson) is the set of a lesson (or null), fluencyList() every real set (samples left out),
     fluencySet(course, id) the document. _setFluency([{ course, doc }]) replaces the sets and _addFluency adds to them, both without a file (the test hook the fixtures use). */
  const fluencyRow = (key) => { const m = fluencyMeta[key]; if (!m) return null; const [course, id] = [key.slice(0, key.indexOf('/')), key.slice(key.indexOf('/') + 1)]; return { course, id, ...m }; };
  const fluencyList = ({ sample = false } = {}) => Object.keys(fluencyMeta).map(fluencyRow).filter(r => r && (sample || !r.sample)).sort((a, b) => (a.course + a.id).localeCompare(b.course + b.id));
  const fluencyFor = (course, lesson) => fluencyList().find(r => r.course === course && r.lesson === lesson) || null;
  const fluencySet = (course, id) => {
    const k = `${course}/${id}`;
    if (fluencyDocs.has(k)) return Promise.resolve(JSON.parse(JSON.stringify(fluencyDocs.get(k))));
    return fluencyMeta[k] ? load(`courses/${course}/${id}.json`) : Promise.resolve(null);
  };
  const setFluency = (rows, add = false) => {
    if (!add) { fluencyMeta = {}; fluencyDocs.clear(); }
    (rows || []).forEach(({ course, doc }) => {
      const k = `${course}/${doc.id}`;
      fluencyDocs.set(k, doc);
      fluencyMeta[k] = { lesson: doc.lesson, title: doc.title, n: doc.n || 20, pass: typeof doc.pass === 'number' ? doc.pass : 0.9, minutes: doc.minutes || 10, families: (doc.families || []).length };   // a registered fixture counts as a real set for this page load
    });
  };
  Object.assign(api, { fluencyList, fluencyFor, fluencySet, _setFluency: setFluency, _addFluency: (rows) => setFluency(rows, true) });
  window.ZQ = window.ZQ || {};
  window.ZQ.content = api;
})();
